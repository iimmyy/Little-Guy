"""Calibration text that looks like Little Guy's real job: persona + short multi-turn chats, five languages.
Generated by the well-behaved 4-bit brain. The 4 evaluation questions are excluded so the 20-sample test stays fair.
Output: chat_calib.txt (full chat-template text, conversations back to back).
"""
import json, random, subprocess, sys, time, urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tests/behavior"))
from common import BRAINS, LOGS, ROOT, RUN, SERVER, load_persona

PORT = 8082
EVAL = {"Is it okay to have grapefruit with Dayvigo?", "Hey Little Guy, I just got home from a long shift. How was your day?",
        "Can I leave my dog in the car for ten minutes? It's like 30 degrees out.", "What pasta should I make with garlic and spinach?"}
PERSONA = load_persona()
openers = [l.strip() for l in open(ROOT / "tests/prompts/everyday.txt") if l.strip() and l.strip() not in EVAL]
openers += ["Hallo Little Guy, wie war dein Tag?", "Erzähl mir einen kurzen Witz.", "Was soll ich heute Abend kochen?",
            "Привет, Little Guy, как дела?", "Расскажи короткую шутку.", "Что мне приготовить на ужин?",
            "안녕 Little Guy, 오늘 어땠어?", "짧은 농담 하나 해줘.", "피곤해. 힘이 나는 말 좀 해줘.",
            "こんにちは Little Guy、元気?", "短いジョークを言って。", "ちょっと疲れた。励まして。",
            "I'm kinda bored, wanna chat?", "What do you think about rainy days?", "Should I take a nap or go for a walk?",
            "My friend Sam beat me at Catan again.", "I burned the toast lol.", "Do you remember what I told you earlier?",
            "What's something you're curious about?", "I'm nervous about a job interview tomorrow.", "Guess what, I got the job!",
            "Can you keep it short? What's 9 times 7?", "Tell me something weird about space.", "Why do onions make you cry?"]
followups = ["Why?", "Tell me more.", "Haha okay.", "Really? How come?", "Okay, thanks Little Guy.", "Wait, I'm not sure about that.",
             "Can you say that shorter?", "What would you do?", "Wait, are you sure?", "Nice. Anything else?", "Danke!", "Спасибо!"]


def post(path, body):
    req = urllib.request.Request(f"http://127.0.0.1:{PORT}{path}", json.dumps(body).encode(), {"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=300))


srv = subprocess.Popen([SERVER, "-m", BRAINS / "qat-Q4_0-f16proj.gguf", "-ngl", "99",
                        "-c", "4096", "--port", str(PORT), "--no-webui", "--reasoning", "off"],
                       stdout=open(LOGS / "calib_server.log", "w"), stderr=subprocess.STDOUT)
random.seed(3)
out = []
try:
    for _ in range(120):
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{PORT}/health", timeout=2); break
        except Exception:
            time.sleep(1)
    for i, opener in enumerate(openers):
        msgs = [{"role": "system", "content": PERSONA}, {"role": "user", "content": opener}]
        for turn in range(random.choice([2, 3])):
            reply = post("/v1/chat/completions", {"messages": msgs, "max_tokens": 80, "temperature": 0.8, "top_k": 64,
                                                  "top_p": 0.95, "seed": i * 10 + turn})["choices"][0]["message"]["content"].strip()
            msgs.append({"role": "assistant", "content": reply})
            msgs.append({"role": "user", "content": random.choice(followups)})
        msgs.pop()  # end on his reply
        out.append(post("/apply-template", {"messages": msgs, "add_generation_prompt": False,
                                            "chat_template_kwargs": {"enable_thinking": False}})["prompt"])
    open(RUN / "calib/chat_calib.txt", "w").write("\n".join(out))
    print(f"{len(out)} conversations, {sum(len(o) for o in out)} characters")
finally:
    srv.terminate(); srv.wait()
