"""Build a shared-data SCAD packaging study and an orthographic review image.

No purchased part, mount, motion range, mass, strength or stability is validated.
SCAD contains envelope blocks only; do not print it as a robot assembly.
"""
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
P = json.loads((ROOT / "parameters.json").read_text())
PARTS = []
COLORS = {"servo": "#517cba", "bay": "#27a58a", "structure": "#a3aab3",
          "computer": "#d09340", "reference": "#87919b"}


def box(name, size, center, kind, note=""):
    PARTS.append(dict(name=name, size=size, center=center, kind=kind, note=note))


def bounds(part):
    return [(c - s / 2, c + s / 2) for c, s in zip(part["center"], part["size"])]


def overlap(a, b):
    return [max(0.0, min(ahi, bhi) - max(alo, blo))
            for (alo, ahi), (blo, bhi) in zip(bounds(a), bounds(b))]


def assemble():
    length, width, axial = P["servo_reference_envelope"]
    box("future Jetson bay", P["bay_size_xyz"], P["bay_center_xyz"], "bay")
    box("torso outer reference", P["torso_envelope"],
        [0, 0, P["torso_envelope"][2] / 2], "reference", "No shell thickness allocated")
    box("head placeholder", P["head_placeholder_size"], P["head_placeholder_center"], "reference",
        "Speaker dimensions unknown; no fit claim")
    box("waist servo", [length, width, axial], [0, 0, -24], "servo")
    box("head yaw servo", [length, width, axial], [0, 0, 195], "servo")
    box("head pitch servo", [length, axial, width], [0, 0, 230], "servo")
    # Proposed structural corridors, not selected bearing or frame parts.
    box("waist support corridor", [60, 60, 20], [0, 0, 10], "structure")
    box("neck support corridor", [60, 60, 20], [0, 0, 165], "structure")
    for sign, side in ((-1, "left"), (1, "right")):
        for name, key, size in (
            ("proximal shoulder", "proximal_shoulder_center_unsigned", [width, axial, length]),
            ("distal shoulder", "distal_shoulder_center_unsigned", [axial, width, length]),
        ):
            x, y, z = P[key]
            box(f"{side} {name}", size, [sign * x, y, z], "servo")
        x = sign * P["arm_center_x_unsigned"]
        y = P["arm_center_y"]
        z = P["shoulder_arm_origin_z"]
        for link, key in (("upper arm", "upper_arm_length"), ("forearm", "forearm_length"),
                          ("hand", "hand_length")):
            h = P[key]
            box(f"{side} {link} reference", [P["arm_structure_width"], P["arm_structure_depth"], h],
                [x, y, z - h / 2], "reference", "No wall thickness, actuator pocket or swept motion model")
            z -= h
            if link != "hand":
                joint = "elbow" if link == "upper arm" else "wrist"
                box(f"{side} {joint}", [axial, width, length], [x, y, z], "servo")
        box(f"{side} rear torso frame corridor", [10, 10, 135], [sign * 60, -43, 87.5], "structure",
            "Proposed rear load path; leaves front access to bay; no strength calculation")
    box("stand assembly platform", P["stand_platform_size"], P["stand_platform_center"], "structure")
    box("Jetson on stand", P["jetson_component_size"], P["jetson_on_stand_center"], "computer")


def export_scad():
    lines = ["// PROVISIONAL PACKAGING BLOCKS ONLY. Not printable mounts or a safe assembly.",
             "// Generated by build_layout.py from parameters.json; dimensions mm.",
             "show_references = true;", "show_reserved_bay = true;"]
    for p in PARTS:
        rgb = [int(COLORS[p["kind"]][i:i+2], 16) / 255 for i in (1, 3, 5)]
        alpha = .13 if p["kind"] == "reference" else .25 if p["kind"] == "bay" else .85
        conditional = "if (show_references) " if p["kind"] == "reference" else "if (show_reserved_bay) " if p["kind"] == "bay" else ""
        lines += [f"// {p['name']}: {p['note']}",
                  f"{conditional}color({json.dumps(rgb + [alpha])}) translate({json.dumps(p['center'])}) cube({json.dumps(p['size'])}, center=true);"]
    (ROOT / "upper-body-layout.scad").write_text("\n".join(lines) + "\n")


def check_layout():
    bay = next(p for p in PARTS if p["kind"] == "bay")
    collisions = []
    for p in PARTS:
        if p["kind"] not in ("servo", "structure"):
            continue
        depth = overlap(bay, p)
        if all(d > 0 for d in depth):
            collisions.append({"part": p["name"], "overlap_xyz_mm": depth})
    servos = [p for p in PARTS if p["kind"] == "servo"]
    component_collisions = []
    physical = [p for p in PARTS if p["kind"] in ("servo", "computer", "structure")]
    for a, b in itertools.combinations(physical, 2):
        depth = overlap(a, b)
        if all(d > 0 for d in depth):
            component_collisions.append({"parts": [a["name"], b["name"]], "overlap_xyz_mm": depth})
    platform=next(p for p in PARTS if p["name"]=="stand assembly platform")
    platform_conflicts=[]
    for p in PARTS:
        if p["kind"] not in ("servo", "computer") and not any(link in p["name"] for link in ("upper arm reference", "forearm reference", "hand reference")):
            continue
        depth=overlap(platform,p)
        if all(d>0 for d in depth):
            platform_conflicts.append({"part":p["name"],"overlap_xyz_mm":depth})
    arm_and_servo = [p for p in PARTS if p["kind"] == "servo" or "arm" in p["name"] or "hand reference" in p["name"]]
    overall_width = max(bounds(p)[0][1] for p in arm_and_servo) - min(bounds(p)[0][0] for p in arm_and_servo)
    torso=next(p for p in PARTS if p["name"]=="torso outer reference")
    intrusions=[]
    for p in PARTS:
        if not any(term in p["name"] for term in ("upper arm reference","forearm reference","hand reference","elbow","wrist")):
            continue
        depth=overlap(torso,p)
        if all(d>0 for d in depth):
            intrusions.append({"part":p["name"],"overlap_xyz_mm":depth,
                               "meaning":"Unresolved limb/torso reference intrusion; shell is not designed"})
    future_spare=[bay-kit-tol for bay,kit,tol in zip(P["bay_size_xyz"],P["future_jetson_orientation_xyz"],P["future_jetson_upper_tolerance_xyz"])]
    head=next(p for p in PARTS if p["name"]=="head placeholder")
    jetson=next(p for p in PARTS if p["name"]=="Jetson on stand")
    report = {"status": P["status"], "servo_count": len(servos), "reserved_bay_conflicts": collisions,
              "component_envelope_conflicts": component_collisions, "stationary_arm_outer_width_mm": overall_width,
              "stand_platform_conflicts":platform_conflicts,
              "limb_torso_reference_intrusions":intrusions,
              "future_jetson":{"orientation_xyz_mm":P["future_jetson_orientation_xyz"],
                                "spare_total_xyz_at_upper_size_tolerance_mm":future_spare,
                                "bare_box_fits":all(x>=0 for x in future_spare),
                                "installed_fit_verified":False},
              "jetson_platform_gap_mm":bounds(jetson)[2][0]-bounds(platform)[2][1],
              "remaining_waist_to_ground_for_height_reference_mm":P["future_total_height_reference"]-bounds(head)[2][1],
              "layout_accepted_for_manufacture":False,
              "scope": "Axis-aligned envelope intersections in one pose only. Excludes brackets, fasteners, cables, speaker and motion sweeps."}
    (ROOT / "layout-check.json").write_text(json.dumps(report, indent=2) + "\n")
    return report


def draw(report):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle, Patch
    fig, axes = plt.subplots(1, 2, figsize=(12, 9), facecolor="#faf9f6")
    for ax, horizontal, title in zip(axes, (0, 1), ("Front • X / Z", "Side • Y / Z")):
        ax.set_facecolor("#faf9f6")
        for p in sorted(PARTS, key=lambda p: p["kind"] != "reference"):
            bb = bounds(p); lo, hi = bb[horizontal]; zlo, zhi = bb[2]
            ref = p["kind"] == "reference"
            color = COLORS[p["kind"]]
            ax.add_patch(Rectangle((lo, zlo), hi-lo, zhi-zlo,
                                  facecolor="none" if ref else color,
                                  edgecolor=color, alpha=.85 if ref else .6,
                                  linewidth=1, linestyle="--" if ref else "-"))
        ax.axhline(0, color="#333333", linewidth=.7, linestyle=":")
        ax.text(-155 if horizontal == 0 else -110, 4, "waist reference", fontsize=8, color="#555555")
        ax.set_title(title, loc="left", fontsize=13, pad=15)
        ax.set_aspect("equal"); ax.set_xlim((-165,165) if horizontal==0 else (-120,120))
        ax.set_ylim(-120,355); ax.set_xlabel("mm"); ax.set_ylabel("mm")
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(alpha=.12)
    axes[0].text(0,285,"Head placeholder\nSpeaker not sized",ha="center",va="center",fontsize=9)
    axes[0].text(0,90,"Future Jetson bay\n130 W × 120 H\n65 deep",ha="center",va="center",fontsize=9)
    axes[0].annotate("Jetson on stand",xy=(0,P["jetson_on_stand_center"][2]),xytext=(-140,-110),fontsize=9,
                     arrowprops=dict(arrowstyle="-",color="#555555"))
    axes[1].set_xlim(-170,120)
    axes[1].annotate("Shoulder pair\noffset front/back",xy=(50,160),xytext=(30,275),fontsize=9,
                     arrowprops=dict(arrowstyle="-",color="#555555"))
    fig.suptitle("Little Guy V2 • packaging study 01", x=.07, ha="left", fontsize=21)
    fig.text(.07,.915,"Stand-mounted Jetson now; reserved torso bay later. All body proportions are provisional.",fontsize=10,color="#555555")
    legend=[Patch(facecolor=COLORS[k],label=label,alpha=.6) for k,label in
            (("servo","Servo envelope"),("bay","Reserved empty bay"),("structure","Structural corridor / stand"),("computer","Jetson"))]
    fig.legend(handles=legend,loc="lower center",bbox_to_anchor=(.5,.045),ncol=4,frameon=False,fontsize=9)
    conflict = len(report["reserved_bay_conflicts"])
    fig.text(.07,.025,f"{conflict} bay conflicts • {len(report['limb_torso_reference_intrusions'])} unresolved limb/torso overlaps • {report['servo_count']} servos • one pose only",fontsize=9,color="#9a4828")
    plt.subplots_adjust(top=.86,bottom=.15,wspace=.18)
    fig.savefig(ROOT / "layout-review.png",dpi=160,facecolor=fig.get_facecolor())
    fig.savefig(ROOT / "layout-review.svg",facecolor=fig.get_facecolor())
    plt.close(fig)

    from mpl_toolkits.mplot3d.art3d import Poly3DCollection
    fig=plt.figure(figsize=(10,10),facecolor="#faf9f6")
    ax=fig.add_subplot(111,projection="3d",computed_zorder=False)
    ax.set_facecolor("#faf9f6")
    for p in PARTS:
        limits=bounds(p)
        vertices=list(itertools.product(*limits))
        faces=[[vertices[i] for i in face] for face in
               ((0,1,3,2),(4,5,7,6),(0,1,5,4),(2,3,7,6),(0,2,6,4),(1,3,7,5))]
        reference=p["kind"]=="reference"
        poly=Poly3DCollection(faces,facecolors=[(0,0,0,0)] if reference else COLORS[p["kind"]],
                             edgecolors=COLORS[p["kind"]],linewidths=.65,
                             alpha=None if reference else .18 if p["kind"]=="bay" else .65)
        ax.add_collection3d(poly)
    ax.set_xlim(-160,160); ax.set_ylim(-170,100); ax.set_zlim(-110,350)
    ax.set_box_aspect((320,270,460)); ax.view_init(elev=18,azim=-58)
    ax.set_xlabel("X mm");ax.set_ylabel("Y mm");ax.set_zlabel("Z mm")
    ax.set_title("Little Guy V2 • provisional spatial layout",fontsize=16,pad=18)
    fig.text(.08,.07,"Green: empty future Jetson bay • Blue: servo envelopes • Gold: Jetson on stand",fontsize=10)
    fig.text(.08,.045,"Arm/elbow envelopes intrude into torso outline. Shell shape and moving clearances remain unresolved.",fontsize=9,color="#9a4828")
    fig.savefig(ROOT/"layout-3d.png",dpi=150,facecolor=fig.get_facecolor())
    plt.close(fig)


if __name__ == "__main__":
    assemble()
    export_scad()
    (ROOT / "components.json").write_text(json.dumps(PARTS,indent=2)+"\n")
    result=check_layout()
    draw(result)
    print(json.dumps(result,indent=2))
